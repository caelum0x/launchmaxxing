"""Turns ``STRATEGY-2026-10-23.md``'s growth move #2 -- "submit launchmaxxing itself to the newer
directories it just added" -- into reusable code instead of a one-off manual pass: runs this
tool's own :mod:`launchmaxxing.content` generator against launchmaxxing's real product profile,
for every catalog directory this project has added but not yet self-submitted to, and writes
ready-to-paste copy into ``launch-evidence/`` -- the project's existing evidence folder, the same
place past manual submissions for other products already left screenshots.

Same philosophy as every other network-touching module in this codebase: **nothing here submits
anything**. Six of the default target directories (PeerPush, Turbo0, Smol Launch, StartupBase,
Microlaunch, Findly Tools) all require creating a free account before a listing goes live (see
their ``catalog.py`` notes) -- account creation and the actual paste-and-click submission stay a
human action. This module's job ends at "here is the exact copy, saved to a file, ready to paste"
and optionally recording the outcome *after* a human confirms they did the real submission
(``mark_submitted=True`` / ``--mark-submitted``), never before.
"""

from __future__ import annotations

import json
import sqlite3
from pathlib import Path
from typing import Any

from launchmaxxing import catalog, content, db, state

#: launchmaxxing's own real product profile -- not a placeholder, kept here the same way a
#: README's own tagline is hardcoded rather than templated from a config file, since this *is*
#: the project's literal identity.
LAUNCHMAXXING_PROFILE = content.ProductProfile(
    name="launchmaxxing",
    tagline="First-100-users toolkit for founders -- local, no accounts",
    problem="Launching a product means manually tracking 80+ directory submissions, writing "
            "platform-specific copy by hand, and losing context across spreadsheets and "
            "browser tabs.",
    audience="founders and small teams launching a SaaS, AI tool or dev tool who do not want "
             "another paid dashboard or account",
    differentiator="82 real launch directories, local SQLite+JSON tracking, template-based copy "
                   "generation, Reddit/HN/Indie Hackers pain-point search and an HTML dashboard "
                   "-- entirely offline, zero account required for any launchmaxxing feature",
    url="https://github.com/caelum0x/launchmaxxing",
    pricing="Free and MIT-licensed",
    subreddit="SideProject",
)

#: The six directories STRATEGY-2026-10-23.md's growth move #2 names explicitly as launchmaxxing's
#: own un-self-submitted targets. Kept as an explicit allowlist, not "every directory in the
#: catalog" -- self-submitting to all 82 in one pass would be spammy, and most don't fit a CLI
#: tool's own category.
DEFAULT_TARGET_PLATFORM_IDS: tuple[str, ...] = (
    "peerpush", "turbo0", "smol_launch", "startupbase", "microlaunch", "findly_tools",
)


def pending_targets(app_state: dict[str, Any], *, product_name: str = "launchmaxxing",
                    platform_ids: tuple[str, ...] = DEFAULT_TARGET_PLATFORM_IDS) -> tuple[dict[str, Any], ...]:
    """Which of ``platform_ids`` do not already have a submitted/live status recorded for
    ``product_name``, in catalog order -- re-running ``dogfood`` after a directory is marked
    submitted stops regenerating copy for it, same idea as ``track``'s stale-directory list."""
    statuses = state.get_platform_statuses(app_state, product_name)
    out = []
    for platform_id in platform_ids:
        platform = catalog.PLATFORM_BY_ID.get(platform_id)
        if platform is None:
            continue
        row = statuses.get(platform_id)
        if row and row.get("status") in ("submitted", "live"):
            continue
        out.append(platform)
    return tuple(out)


def _render_evidence_markdown(platform: dict[str, Any], tagline: dict[str, Any], description: dict[str, Any],
                              profile: content.ProductProfile) -> str:
    return "\n".join([
        f"# Dogfood submission copy -- {platform['name']}", "",
        f"- Submit URL: {platform['url']}",
        f"- Account required: {'no' if platform['account_free'] else 'yes (free account, per catalog.py)'}",
        f"- Catalog note: {platform['note']}", "",
        "## Tagline / one-line pitch", f"_{tagline['length']}/{tagline['limit']} chars_", "",
        tagline["text"], "",
        "## Description", f"_{description['length']}/{description['limit']} chars_", "",
        description["text"], "",
        "## Product URL to paste into the form", profile.url, "",
        "---",
        ("Generated by `launchmaxxing dogfood` -- paste the above into the submission form "
         "above by hand; this file is evidence of what was submitted, not a submission itself."),
        "",
    ])


def run(app_state: dict[str, Any], conn: sqlite3.Connection, *, evidence_dir: Path | str,
       product_name: str = "launchmaxxing", profile: content.ProductProfile = LAUNCHMAXXING_PROFILE,
       platform_ids: tuple[str, ...] = DEFAULT_TARGET_PLATFORM_IDS,
       mark_submitted: bool = False) -> list[dict[str, Any]]:
    """Generate ready-to-paste copy for every pending target directory (see
    :func:`pending_targets`): write one Markdown evidence file per directory into
    ``evidence_dir``, save the generated copy as a content draft in the local database (same
    effect as ``content ... --save``), and -- only when ``mark_submitted=True``, i.e. a human
    has confirmed they actually did the paste-and-click submission -- record a ``submitted``
    status via the same tracker ``launchmaxxing submit`` writes to, with a note pointing back at
    the evidence file. Returns one summary row per directory processed, in catalog order."""
    out_dir = Path(evidence_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    results: list[dict[str, Any]] = []
    for platform in pending_targets(app_state, product_name=product_name, platform_ids=platform_ids):
        tagline = content.product_hunt_tagline(profile)
        description = content.product_hunt_description(profile)
        markdown = _render_evidence_markdown(platform, tagline, description, profile)
        evidence_path = out_dir / f"launchmaxxing-{platform['id']}-dogfood-copy.md"
        evidence_path.write_text(markdown, encoding="utf-8")
        db.add_content_draft(conn, product_name=product_name, platform=platform["id"], kind="dogfood",
                             body=json.dumps({"tagline": tagline, "description": description}))
        marked = False
        if mark_submitted:
            state.set_platform_status(
                app_state, product_name=product_name, platform_id=platform["id"], status="submitted",
                note=f"Dogfooded via launchmaxxing dogfood; copy at {evidence_path.name}.",
            )
            db.log_submission_event(conn, product_name=product_name, platform_id=platform["id"],
                                    status="submitted",
                                    note="dogfood --mark-submitted: human confirmed the real submission.")
            marked = True
        results.append({
            "platform_id": platform["id"], "name": platform["name"], "url": platform["url"],
            "account_free": platform["account_free"], "evidence_path": str(evidence_path),
            "marked_submitted": marked,
        })
    return results


__all__ = ["DEFAULT_TARGET_PLATFORM_IDS", "LAUNCHMAXXING_PROFILE", "pending_targets", "run"]
